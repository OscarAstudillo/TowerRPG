// --- FUNCIÓN HELPER ---
export function getLevelData(biomeKey, levelId) {
    // Si levelId es > 10, lo ajustamos al ciclo 1-10 para obtener stats de dificultad
    let safeLevel = levelId;
    if (safeLevel > 10) safeLevel = ((levelId - 1) % 10) + 1;

    // Obtener configuración de stats (1-10)
    const config = LEVEL_CONFIG[safeLevel];
    
    // Obtener mapa específico por NOMBRE CLAVE (forest_1, mountain_5, etc.)
    const mapKey = `${biomeKey}_${safeLevel}`;
    const mapGrid = MAPS[mapKey] || MAPS['forest_1']; // Fallback a nivel 1 si falla

    // CALCULAR SPAWN MULTIPLIER (50% más enemigos por ruta extra)
    let paths = 1;
    if (safeLevel >= 4 && safeLevel <= 7) paths = 2;
    if (safeLevel >= 8) paths = 3;

    // Fórmula: 1 camino = x1.0, 2 caminos = x1.5, 3 caminos = x2.0
    const spawnMultiplier = 1 + ((paths - 1) * 0.5);

    return {
        id: levelId, // ID real (ej: 25)
        name: `${BIOMES[biomeKey].name} - Nivel ${safeLevel}`,
        mapGrid: mapGrid,
        spawnMultiplier: spawnMultiplier,
        pathCount: paths, // Dato útil para debug
        ...config // Hereda waves, hpMult, etc.
    };
}