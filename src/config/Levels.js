// --- FUNCIÓN DE ENRIQUECIMIENTO (TEXTURIZACIÓN ALEATORIA) ---
function enrichMap(originalGrid) {
    // Clona la matriz para no modificar la original
    const newGrid = originalGrid.map(row => [...row]);
    
    for (let r = 0; r < newGrid.length; r++) {
        for (let c = 0; c < newGrid[0].length; c++) {
            // Si es pasto (0), mezcla aleatoriamente con 3, 4, 5
            if (newGrid[r][c] === 0) {
                const rand = Math.random();
                if (rand < 0.9) newGrid[r][c] = 0;      // 70% Pasto base
                else if (rand < 0.95) newGrid[r][c] = 3; // 10% Pasto variante 1
                else if (rand < 0.97) newGrid[r][c] = 4; // 10% Pasto variante 2
                else newGrid[r][c] = 5;                 // 10% Pasto variante 3
            }
        }
    }
    return newGrid;
}

// --- FUNCIÓN HELPER ---
export function getLevelData(biomeKey, levelId) {
    let safeLevel = levelId;
    if (safeLevel > 10) safeLevel = ((levelId - 1) % 10) + 1;

    const config = LEVEL_CONFIG[safeLevel];
    const mapKey = `${biomeKey}_${safeLevel}`;
    
    // Obtener mapa base
    let baseGrid = MAPS[mapKey] || MAPS['forest_1'];
    
    // Enriquecer mapa (texturizar)
    const mapGrid = enrichMap(baseGrid);

    let paths = 1;
    if (safeLevel >= 4 && safeLevel <= 7) paths = 2;
    if (safeLevel >= 8) paths = 3;

    const spawnMultiplier = 1 + ((paths - 1) * 0.5);

    return {
        id: levelId,
        name: `${BIOMES[biomeKey].name} - Nivel ${safeLevel}`,
        mapGrid: mapGrid,
        spawnMultiplier: spawnMultiplier,
        pathCount: paths,
        ...config
    };
}