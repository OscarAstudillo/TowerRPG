export const LEVEL_CONFIG = {};

// Dificultad incremental
const DIFFICULTY = [
    { waves: 3, hp: 1.0, drop: 0.15 },
    { waves: 4, hp: 1.2, drop: 0.18 },
    { waves: 5, hp: 1.5, drop: 0.20 },
    { waves: 6, hp: 2.0, drop: 0.22 },
    { waves: 7, hp: 2.5, drop: 0.25 },
    { waves: 8, hp: 3.0, drop: 0.28 },
    { waves: 9, hp: 4.0, drop: 0.30 },
    { waves: 10, hp: 5.5, drop: 0.35 },
    { waves: 12, hp: 7.0, drop: 0.40 },
    { waves: 15, hp: 10.0, drop: 0.50 }
];

for (let i = 1; i <= 30; i++) {
    let biomeKey = 'forest';
    if (i > 10) biomeKey = 'mountain';
    if (i > 20) biomeKey = 'volcano';

    let diffIndex = (i - 1) % 10;
    const diff = DIFFICULTY[diffIndex];

    LEVEL_CONFIG[i] = {
        id: i,
        mapGrid: LEVEL_MAPS[i], // Asignamos la matriz correspondiente
        biome: biomeKey,
        waves: diff.waves,
        hpMult: diff.hp,
        dropRate: diff.drop,
        tier: Math.ceil(i / 10)
    };
}

export function getLevelData(biomeKey, levelId) {
    const config = LEVEL_CONFIG[levelId];
    return {
        id: levelId,
        name: `${BIOMES[biomeKey].name} - Nivel ${levelId}`,
        mapGrid: config.mapGrid,
        spawnMultiplier: 1,
        ...config
    };
}