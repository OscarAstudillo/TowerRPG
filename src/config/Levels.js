export function getLevelData(biomeKey, levelId) {
    let safeLevel = levelId;
    if (safeLevel > 10) safeLevel = ((levelId - 1) % 10) + 1;

    const config = LEVEL_CONFIG[safeLevel];
    const mapKey = `${biomeKey}_${safeLevel}`;
    const mapGrid = MAPS[mapKey] || MAPS['forest_1'];

    let paths = 1;
    if (safeLevel >= 4 && safeLevel <= 7) paths = 2;
    if (safeLevel >= 8) paths = 3;

    const spawnMultiplier = 1 + ((paths - 1) * 0.5);

    return {
        id: levelId,
        name: `${BIOMES[biomeKey].name} - Nivel ${safeLevel}`,
        mapGrid: mapGrid,
        spawnMultiplier: spawnMultiplier,
        pathCount: paths,
        ...config
    };
}