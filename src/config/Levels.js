// --- FUNCIÓN HELPER ---
export function getLevelData(biomeKey, levelId) {
    // Si levelId es > 10, lo ajustamos al ciclo 1-10
    let safeLevel = levelId;
    if (safeLevel > 10) safeLevel = ((levelId - 1) % 10) + 1;

    // Obtener stats
    const config = LEVEL_CONFIG[safeLevel];
    
    // Obtener mapa específico por NOMBRE CLAVE
    const mapKey = `${biomeKey}_${safeLevel}`;
    const mapGrid = MAPS[mapKey] || MAPS['forest_1']; // Fallback por seguridad

    // CALCULAR MULTIPLICADOR SEGÚN RUTAS
    // 1-3 = 1 ruta, 4-7 = 2 rutas, 8-10 = 3 rutas
    let paths = 1;
    if (safeLevel >= 4 && safeLevel <= 7) paths = 2;
    if (safeLevel >= 8) paths = 3;

    // Fórmula: 1 camino = x1.0, 2 caminos = x1.5, 3 caminos = x2.0
    const spawnMultiplier = 1 + ((paths - 1) * 0.5);

    return {
        id: levelId,
        name: `${BIOMES[biomeKey].name} - Nivel ${safeLevel}`,
        mapGrid: mapGrid,
        spawnMultiplier: spawnMultiplier,
        pathCount: paths,
        ...config // Hereda waves, hpMult, dropRate, tier
    };
}