// --- FUNCIÓN DE GENERACIÓN (SOLO INTERPOLACIÓN) ---
// Convierte los puntos de control P0-P3 en una lista de puntos pixel a pixel para el movimiento
function getBezierPoints(p0, p1, p2, p3) {
    const points = [];
    for (let t = 0; t <= 1.01; t += 0.005) { 
        const x = Math.pow(1 - t, 3) * p0[0] + 3 * Math.pow(1 - t, 2) * t * p1[0] + 3 * (1 - t) * Math.pow(t, 2) * p2[0] + Math.pow(t, 3) * p3[0];
        const y = Math.pow(1 - t, 3) * p0[1] + 3 * Math.pow(1 - t, 2) * t * p1[1] + 3 * (1 - t) * Math.pow(t, 2) * p2[1] + Math.pow(t, 3) * p3[1];
        points.push({ x, y });
    }
    return points;
}

export function getLevelData(biomeKey, levelId) {
    // 1. Obtener definición MANUAL
    const mapKey = `${biomeKey}_${levelId}`;
    const layout = STATIC_LEVELS[mapKey] || STATIC_LEVELS['forest_1']; // Fallback seguro
    
    // 2. Procesar Caminos (Convertir control points a trayectoria)
    const paths = layout.paths.map(def => getBezierPoints(def.p0, def.p1, def.p2, def.p3));
    
    // 3. Usar Slots Estáticos Directamente
    const towerSlots = layout.slots || [];

    // 4. Calcular Multiplicador de Enemigos según cantidad de caminos
    const pathCount = paths.length;
    const spawnMultiplier = 1 + ((pathCount - 1) * 0.5);

    return {
        id: levelId,
        name: `${BIOMES[biomeKey].name} - Nivel ${levelId}`,
        paths: paths,
        towerSlots: towerSlots,
        spawnMultiplier: spawnMultiplier,
        pathCount: pathCount
    };
}